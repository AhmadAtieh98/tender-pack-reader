def test_two_writes_are_byte_identical(tmp_path):
    """One write here, one in another process (other hash seed) at least 2 s later (zip times have
    2 s resolution), into another directory: every file must be identical."""
    start = time.monotonic()
    a = write_all(tmp_path / "a")
    time.sleep(max(0.0, 2.1 - (time.monotonic() - start)))
    code = ("import sys; from pathlib import Path; sys.path[:0] = [sys.argv[1], sys.argv[1] + '/tests']; "
            "import test_render; test_render.write_all(Path(sys.argv[2]))")
    env = {**os.environ, "PYTHONHASHSEED": "12345"}
    subprocess.run([sys.executable, "-c", code, str(ROOT), str(tmp_path / "b")], check=True, env=env, cwd=tmp_path)
    b = [tmp_path / "b" / p.relative_to(tmp_path / "a") for p in a]
    assert sorted(p.suffix for p in a) == [".csv", ".csv", ".json", ".json", ".pdf", ".xlsx"]
    for pa, pb in zip(a, b):
        assert pa.read_bytes() == pb.read_bytes(), pa.name
