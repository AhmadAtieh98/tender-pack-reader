def test_a3_one_page_with_key_texts(tmp_path):
    a3 = a3_input()
    path = tmp_path / "a3.pdf"
    info = write_a3_pdf(a3, path)
    assert info["pages"] == 1 and A3_SCALE_LOW <= info["scale"] <= 1 and info["spare_pt"] >= 0
    doc = pymupdf.open(path)
    assert doc.page_count == 1
    page = doc[0]
    assert (round(page.rect.width), round(page.rect.height)) == (595, 842)
    # compared after NFKC without whitespace: MuPDF extracts the "fi" ligature and wraps at hyphens
    def flat(s: str) -> str:
        return "".join(unicodedata.normalize("NFKC", s).split())
    text = flat(page.get_text())
    for key in (a3["title"], a3["subtitle"], a3["banner"], "Rejection stated in the documents",
                "Explicit document wording only.", "VOL-I-8.6-01", "VOL-IV-p6-r1",
                "“Failure to submit the certificate shall render the Proposal non-responsive.”",
                "ADD-02 §9.1 p3", "confidence high", "REINSTATED-AMENDED", "image reading PENDING review",
                "R&D <annexes>", "Mandatory, no stated consequence", "None.", "Could not resolve", "U-01",
                "Competent authority not named in the pack.", "owner: Bid manager", a3["footer"]):
        assert flat(key) in text, key
    meta = doc.metadata
    assert meta["producer"] == "tenderpack" and meta["creationDate"] == meta["modDate"] == "D:20261001000000Z"
    assert b"/ID" not in path.read_bytes()


def test_a3_arabic_is_shaped_and_right_to_left(tmp_path):
    path = tmp_path / "a3.pdf"
    write_a3_pdf(a3_input(), path)
    page = pymupdf.open(path)[0]
    assert any("Noto Naskh Arabic" in f[3] for f in page.get_fonts())   # bundled with PyMuPDF
    # MuPDF extracts shaped Arabic as presentation forms (shaping happened); NFKC gives the letters
    words = [(w[0], w[1], unicodedata.normalize("NFKC", w[4])) for w in page.get_text("words")]
    first = [(x, y) for x, y, t in words if t == "يؤدي"]
    later = [(x, y) for x, y, t in words if t == "استبعاد"]
    assert len(first) == len(later) == 2                        # text and consequence of VOL-IV-p6-r1
    for (x1, y1), (x2, y2) in zip(sorted(first), sorted(later)):
        assert abs(y1 - y2) < 1 and x1 > x2                     # first word is to the right


def test_a3_overflow_raises_and_writes_nothing(tmp_path):
    path = tmp_path / "a3.pdf"
    with pytest.raises(A3OverflowError, match="one A4 page"):
        write_a3_pdf(a3_input(300), path)
    assert not path.exists()


