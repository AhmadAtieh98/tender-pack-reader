def test_a1_files_csv_and_json(tmp_path):
    a1 = a1_input()
    paths = write_a1(a1, tmp_path)
    assert [p.name for p in paths] == ["a1.json", "a1.csv", "a1.xlsx"] and all(p.is_file() for p in paths)
    assert json.loads(paths[0].read_text(encoding="utf-8")) == a1

    raw = paths[1].read_bytes()
    assert raw.startswith(b"\xef\xbb\xbf")                      # BOM, so Excel reads Arabic
    assert raw.count(b"\r\n") == 4 and b"\n" not in raw.replace(b"\r\n", b"")
    rows = list(csv.reader(io.StringIO(raw.decode("utf-8-sig"), newline="")))
    assert rows[0] == [c["header"] for c in a1["columns"]]
    assert rows[1] == ["VOL-I-8.6-01", "Local Content Certificate, not less than 30%",
                       "certificate; ratio calculation", "ACTIVE", "DELETED (by ADD-01/4.1)",
                       "REINSTATED-AMENDED", "TRUE", "", "Pending human review"]
    assert rows[2][1] == AR and rows[2][2] == "" and rows[2][6:8] == ["FALSE", "0.35"]
    assert rows[3][1] == "=Form 4-G is not a formula" and rows[3][7] == "3" and rows[3][8] == ""


def test_a1_xlsx_structure_and_styles(tmp_path):
    a1 = a1_input()
    wb = openpyxl.load_workbook(write_a1(a1, tmp_path)[2])
    assert wb.sheetnames == ["A1 register", "Dates", "Issues"]
    ws = wb["A1 register"]
    assert ws["A1"].value == a1["title"] and ws["A1"].font.b
    assert ws["A2"].value == a1["notice"] and ws["A2"].font.i
    assert ws.freeze_panes == "A5" and ws.auto_filter.ref == "A4:I7"
    assert [c.value for c in ws[4]] == [c["header"] for c in a1["columns"]] and all(c.font.b for c in ws[4])
    assert ws.column_dimensions["B"].width == 60 and ws.column_dimensions["A"].width == 16
    assert ws["B5"].alignment.wrap_text and ws["B5"].alignment.vertical == "top"

    def fill(ref):
        c = ws[ref]
        return c.fill.fgColor.rgb[-6:] if c.fill.fill_type == "solid" else None
    # rows 5-7, status columns D-F
    assert [fill(r) for r in ("D5", "E5", "F5")] == [None, "D9D9D9", "E2EFDA"]
    assert [fill(r) for r in ("D6", "E6", "F6")] == [None, "FFF2CC", "FCE4D6"]
    assert [fill(r) for r in ("D7", "E7", "F7")] == ["F2F2F2", "F2F2F2", "E2EFDA"]
    assert fill("A5") is None and fill("I5") is None
    assert ws["I5"].font.i and not ws["I6"].font.i            # "pending" in a status-like column
    assert ws["B6"].value == AR                                 # Arabic as given, not reordered
    assert ws["C5"].value == "certificate; ratio calculation" and ws["C6"].value is None
    assert ws["G5"].value is True and ws["H6"].value == 0.35 and ws["H5"].value is None
    assert ws["B7"].value == "=Form 4-G is not a formula" and ws["B7"].data_type == "s"

    for name, n_rows in (("Dates", 2), ("Issues", 1)):
        sh, spec = wb[name], a1["sheets"][name]
        assert sh.freeze_panes == "A2" and sh.auto_filter.ref == f"A1:{'BC'[len(spec['columns']) - 2]}{1 + n_rows}"
        assert [c.value for c in sh[1]] == [c["header"] for c in spec["columns"]] and all(c.font.b for c in sh[1])
    assert wb["Issues"]["B1"].value == "Issue" and wb["Issues"].column_dimensions["B"].width == 50


def test_a1_xlsx_has_no_save_time(tmp_path):
    path = write_a1(a1_input(), tmp_path)[2]
    wb = openpyxl.load_workbook(path)
    assert wb.properties.created == FIXED_TIME and wb.properties.modified == FIXED_TIME
    assert wb.properties.creator == wb.properties.lastModifiedBy == "tenderpack"
    with zipfile.ZipFile(path) as z:
        infos = z.infolist()
    assert infos[0].filename == "[Content_Types].xml"
    assert [i.filename for i in infos[1:]] == sorted(i.filename for i in infos[1:])
    assert {i.date_time for i in infos} == {(1980, 1, 1, 0, 0, 0)}
    assert {i.compress_type for i in infos} == {zipfile.ZIP_DEFLATED}


