def test_unsupported_values_and_duplicate_keys_are_refused(tmp_path):
    bad = {"columns": [_col("a", "A")], "rows": [{"a": {"x", "y"}}]}
    with pytest.raises(TypeError):
        write_csv_json(bad, tmp_path, "bad")
    with pytest.raises(ValueError, match="duplicate"):
        write_csv_json({"columns": [_col("a", "A"), _col("a", "B")], "rows": []}, tmp_path, "dup")
    assert not list(tmp_path.iterdir())                         # nothing written on failure


