def write_all(out: Path) -> list[Path]:
    """Every writer once; also run in a subprocess by the determinism test."""
    paths = write_a1(a1_input(), out / "a1")
    paths += write_csv_json(a2_input(), out / "a2", "a2_changes")
    write_a3_pdf(a3_input(), out / "a3" / "a3.pdf")
    return paths + [out / "a3" / "a3.pdf"]


